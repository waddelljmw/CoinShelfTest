// Step 35 (v0.129.0): "What do you have?" box, + Add this coin, value line under Grade, Gain wording.
const { chromium } = require("./_compat");
const path = require("path");
const ok = (name, v) => { console.log((v ? "PASS " : "FAIL ") + name); if (!v) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; p.on("pageerror", (e) => errors.push(e.message));
  await p.goto("file://" + path.resolve(__dirname, "../index.html")); await p.waitForTimeout(300);
  const val = () => p.evaluate(() => ({ y: draft.year, m: draft.mint, t: draft.typeId, box: $("#typeSearch").value, listHidden: $("#typeList").hidden, gold: !!document.querySelector(".grade-row.next-up"), focus: document.activeElement && document.activeElement.id, use: $("#useValue").hidden ? "" : $("#useValue").textContent }));
  await p.evaluate(() => openCoinForm(null)); await p.waitForTimeout(300);
  ok("box is above Year", await p.evaluate(() => !!($("#typeSearch").compareDocumentPosition($("[data-f=year]")) & Node.DOCUMENT_POSITION_FOLLOWING)));
  await p.fill("#typeSearch", "1885 cc mo");
  await p.click('[data-act=whatPick][data-id="morgan-dollar"]'); await p.waitForTimeout(200);
  let r = await val();
  ok("type, year, mint filled", r.t === "morgan-dollar" && r.y === "1885" && r.m === "CC");
  ok("box shows tick, list closed, keyboard closed, Grade outlined", /^✓ 1885-CC Morgan/.test(r.box) && r.listHidden && r.focus !== "typeSearch" && r.gold);
  ok("value line shows value and source", /^Value: \$[\d,.]+ \(.+\)$/.test(r.use));
  await p.fill("[data-f=value]", "99"); await p.waitForTimeout(100);
  ok("value line hides once Value is typed", (await val()).use === "");
  await p.fill("[data-f=year]", "1884"); await p.waitForTimeout(100);
  ok("changing the year drops the tick", !(await val()).box.startsWith("✓"));
  await p.evaluate(() => { closeSheet(); openCoinForm(null); }); await p.waitForTimeout(200);
  await p.fill("#typeSearch", "1964 quarter");
  ok("1964 quarter is silver only", await p.evaluate(() => { const ids = [...document.querySelectorAll("[data-act=whatPick]")].map((x) => x.dataset.id); return ids.length > 0 && ids.every((i) => TYPE_BY_ID[i].metal === "Silver"); }));
  await p.fill("#typeSearch", "peace");
  ok("no year: the type list as before", await p.evaluate(() => !!document.querySelector('#typeList [data-act=pickType][data-id="peace-dollar"]')));
  await p.evaluate(() => { closeSheet(); lookupOpen({ dataset: { t: "washington-silver", y: "1964", m: "D" } }); }); await p.waitForTimeout(200);
  await p.click("[data-act=lookupAdd]"); await p.waitForTimeout(300);
  r = await val();
  ok("+ Add this coin opens Add coin filled", r.t === "washington-silver" && r.y === "1964" && r.m === "D" && r.box.startsWith("✓"));
  await p.evaluate(() => { closeSheet(); saveCoin({ ...blankCoin(), typeId: "morgan-dollar", typeName: "Morgan", year: "1885", paid: "20", value: "30" }); go("home"); render(); }); await p.waitForTimeout(300);
  ok("Gain small line", /\+50\.0% · needs cost \+ value · inherited not counted/.test(await p.evaluate(() => document.body.innerText)));
  ok("no page errors", errors.length === 0);
  if (errors.length) console.log(errors);
  await p.evaluate(() => { openCoinForm(null); }); await p.waitForTimeout(200);
  await b.close();
})();
